-- Guest chat identities must not get marketplace permissions via the default profile role.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  -- Guest support users are stored directly in auth.users; no marketplace profile is needed.
  if coalesce(new.is_anonymous, false) then
    return new;
  end if;
  insert into public.profiles (id, full_name, phone, user_type, is_active)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), new.phone,
    case when new.raw_user_meta_data->>'user_type' in ('Trader','Driver')
      then new.raw_user_meta_data->>'user_type' else 'Trader' end, true)
  on conflict (id) do nothing;
  return new;
end;
$$;
update public.profiles p set is_active = false from auth.users u where u.id = p.id and u.is_anonymous and p.is_active;
-- Human-to-human support chat for TradeMaster.
create table if not exists public.support_conversations (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'open' check (status in ('open','closed')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.support_messages (
 id bigint generated by default as identity primary key,
 conversation_id uuid not null references public.support_conversations(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 body text not null check (length(btrim(body)) between 1 and 4000),
 created_at timestamptz not null default now()
);
alter table public.support_conversations drop constraint if exists support_conversations_user_id_fkey;
alter table public.support_conversations add constraint support_conversations_user_id_fkey
  foreign key (user_id) references auth.users(id) on delete cascade;
alter table public.support_messages drop constraint if exists support_messages_sender_id_fkey;
alter table public.support_messages add constraint support_messages_sender_id_fkey
  foreign key (sender_id) references auth.users(id) on delete cascade;
create index if not exists support_conversations_user_idx on public.support_conversations(user_id, updated_at desc);
create index if not exists support_messages_conversation_idx on public.support_messages(conversation_id, created_at);
alter table public.support_conversations enable row level security;
alter table public.support_messages enable row level security;
grant select, insert on public.support_conversations to authenticated;grant delete on public.support_conversations to authenticated;
drop policy if exists "admins delete support conversations" on public.support_conversations;
create policy "admins delete support conversations" on public.support_conversations
for delete to authenticated
using ((auth.jwt()->'app_metadata'->>'is_admin') = 'true');
grant select, insert on public.support_messages to authenticated;
grant usage, select on sequence public.support_messages_id_seq to authenticated;
drop policy if exists "customers and admins read support conversations" on public.support_conversations;
create policy "customers and admins read support conversations" on public.support_conversations for select to authenticated
using (user_id = auth.uid() or (auth.jwt()->'app_metadata'->>'is_admin') = 'true');
drop policy if exists "customers create own support conversations" on public.support_conversations;
create policy "customers create own support conversations" on public.support_conversations for insert to authenticated
with check (user_id = auth.uid() and status = 'open' and (auth.jwt()->>'is_anonymous' = 'true' or public.is_active_marketplace_user('Trader') or public.is_active_marketplace_user('Driver')));
drop policy if exists "participants read support messages" on public.support_messages;
create policy "participants read support messages" on public.support_messages for select to authenticated
using ((auth.jwt()->'app_metadata'->>'is_admin') = 'true' or exists (select 1 from public.support_conversations c where c.id = conversation_id and c.user_id = auth.uid()));
drop policy if exists "participants send support messages" on public.support_messages;
create policy "participants send support messages" on public.support_messages for insert to authenticated
with check (sender_id = auth.uid() and ((auth.jwt()->'app_metadata'->>'is_admin') = 'true' or exists
(select 1 from public.support_conversations c where c.id = conversation_id and c.user_id = auth.uid() and c.status = 'open')));
create or replace function public.touch_support_conversation()
returns trigger language plpgsql security definer set search_path = '' as $$
begin update public.support_conversations set updated_at = now() where id = new.conversation_id; return new; end;
$$;
drop trigger if exists support_message_touch_conversation on public.support_messages;
create trigger support_message_touch_conversation after insert on public.support_messages for each row execute function public.touch_support_conversation();
do $$
begin
 if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='support_conversations') then alter publication supabase_realtime add table public.support_conversations; end if;
 if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='support_messages') then alter publication supabase_realtime add table public.support_messages; end if;
end;
$$;
