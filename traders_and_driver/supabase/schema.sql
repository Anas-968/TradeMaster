-- TradeMaster marketplace schema. Run in the Supabase SQL editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  user_type text not null check (user_type in ('Trader', 'Driver', 'Admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Existing projects may already have profiles without newer columns.
alter table public.profiles
  add column if not exists is_active boolean not null default true;

create table if not exists public.loads (
  id bigint generated by default as identity primary key,
  trader_id uuid not null references public.profiles(id),
  driver_id uuid references public.profiles(id),
  product text not null,
  description text not null default '',
  pickup_location text not null,
  delivery_location text not null,
  weight text not null default '',
  status text not null default 'Available'
    check (status in ('Available', 'Accepted', 'In transit', 'Delivered', 'Cancelled')),
  created_at timestamptz not null default now(),
  accepted_at timestamptz
);

create index if not exists loads_status_created_idx on public.loads(status, created_at desc);
create index if not exists loads_trader_idx on public.loads(trader_id, created_at desc);
create index if not exists loads_driver_idx on public.loads(driver_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.loads enable row level security;
grant select, update (is_active) on public.profiles to authenticated;
grant select, insert on public.loads to authenticated;

-- Remove any older/custom policies first. Policies that query profiles from a
-- profiles policy cause PostgreSQL's infinite-recursion error (42P17).
do $$
declare policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public' and tablename in ('profiles', 'loads')
  loop
    execute format('drop policy %I on %I.%I', policy_row.policyname,
      policy_row.schemaname, policy_row.tablename);
  end loop;
end;
$$;

-- Security-definer lookup avoids evaluating profiles RLS from load policies.
create or replace function public.is_active_marketplace_user(required_type text)
returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.user_type = required_type and p.is_active
  );
$$;
revoke all on function public.is_active_marketplace_user(text) from public;
grant execute on function public.is_active_marketplace_user(text) to authenticated;

create policy "profiles readable by signed in users" on public.profiles
  for select to authenticated using (id = auth.uid() or (auth.jwt()->'app_metadata'->>'is_admin') = 'true');
create policy "users create own profile" on public.profiles
  for insert to authenticated with check (id = auth.uid() and user_type in ('Trader','Driver'));
create policy "admins manage profiles" on public.profiles
  for all to authenticated using ((auth.jwt()->'app_metadata'->>'is_admin') = 'true')
  with check ((auth.jwt()->'app_metadata'->>'is_admin') = 'true');

create policy "loads visible to marketplace" on public.loads
  for select to authenticated using (true);
create policy "traders create loads" on public.loads
  for insert to authenticated with check (
    trader_id = auth.uid() and public.is_active_marketplace_user('Trader')
  );
-- Drivers claim loads through a checked database function, never by editing rows directly.
revoke update on public.loads from authenticated;
drop function if exists public.accept_load(bigint);
create function public.accept_load(p_load_id bigint)
returns bigint language plpgsql security definer set search_path = '' as $$
declare accepted_id bigint;
begin
  if auth.uid() is null or not exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.user_type = 'Driver' and p.is_active
  ) then raise exception 'Only active drivers may accept loads'; end if;
  update public.loads set status = 'Accepted', driver_id = auth.uid(), accepted_at = now()
    where id = p_load_id and status = 'Available' returning id into accepted_id;
  if accepted_id is null then raise exception 'This load is no longer available'; end if;
  return accepted_id;
end;
$$;
revoke all on function public.accept_load(bigint) from public;
grant execute on function public.accept_load(bigint) to authenticated;

-- Auth signup hook: create profiles from user metadata, if the hook is enabled.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name, phone, user_type)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), new.phone,
    case when new.raw_user_meta_data->>'user_type' in ('Trader','Driver')
      then new.raw_user_meta_data->>'user_type' else 'Trader' end)
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill accounts that existed before this schema was installed.
insert into public.profiles (id, full_name, phone, user_type)
select u.id, coalesce(u.raw_user_meta_data->>'full_name',''), u.phone,
  case when u.raw_user_meta_data->>'user_type' in ('Trader','Driver')
    then u.raw_user_meta_data->>'user_type' else 'Trader' end
from auth.users u
on conflict (id) do nothing;

